//! `previews` section of `AssetService` — the `generate-previews`
//! operation. One service loop serves the CLI command and the web
//! maintenance job (architecture audit F18): both translate their input
//! into a [`PreviewScope`] plus [`PreviewOptions`], render the per-item
//! [`PreviewEvent`]s their way (`--log` lines, SSE progress) and read the
//! [`PreviewGenerateResult`] counters.
//!
//! Free functions and result types live in the parent `asset_service` module.

use super::*;

/// Which media files get previews.
#[derive(Debug, Clone)]
pub enum PreviewScope {
    /// Files or directories on disk (the CLI's `PATHS` form). Each file is
    /// looked up in the catalog by volume and path, then by content hash;
    /// files the catalog does not know are reported but not counted.
    Paths(Vec<PathBuf>),
    /// One asset (id or unique prefix).
    Asset(String),
    /// Every asset in the catalog.
    All,
}

/// Options of one preview-generation run.
#[derive(Default)]
pub struct PreviewOptions {
    /// Only consider file locations on this volume (label). Catalog scopes
    /// only; `Paths` already names its files.
    pub volume: Option<String>,
    /// Which file types take part (`--include` / `--skip` groups).
    pub filter: FileTypeFilter,
    /// Regenerate previews that already exist.
    pub force: bool,
    /// Catalog scopes only: regenerate the preview of assets whose best
    /// variant is not their first one (a higher-priority variant joined
    /// the asset after the preview was made); every other asset is
    /// skipped.
    pub upgrade: bool,
    /// Also generate the high-resolution smart preview.
    pub smart: bool,
}

/// What happened to one item of a preview run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum PreviewStatus {
    /// A preview is in place: written now, or (without `force`) already
    /// present — the generator reports both the same way.
    Generated,
    /// A preview was regenerated from a better variant (`upgrade`).
    Upgraded,
    /// The format has no preview, or the external tool it needs is missing.
    Skipped,
    /// Catalog scopes: the asset has no variants.
    NoVariant,
    /// Catalog scopes: the variant's format is outside the type filter.
    Filtered,
    /// Catalog scopes with `upgrade`: the best variant is already the first.
    NotUpgradable,
    /// Catalog scopes: no online volume holds a file of the variant. The
    /// offline volumes that do are collected in
    /// [`PreviewGenerateResult::offline_blockers`].
    Unreachable,
    /// `Paths` scope: the file is not in the catalog (not counted).
    NotInCatalog,
    /// The regular preview failed (message is the full error chain).
    Failed(String),
    /// The regular preview succeeded (or was skipped) but the smart preview
    /// failed.
    SmartFailed(String),
    /// Catalog scopes: the video/audio metadata backfill that precedes the
    /// preview failed; the preview is still attempted.
    MetadataBackfillFailed(String),
}

/// One item of a preview run, as the callback sees it.
pub struct PreviewEvent<'a> {
    /// The media file the preview is derived from; `None` when no file was
    /// reachable.
    pub path: Option<&'a Path>,
    /// The owning asset; `None` in the `Paths` scope, which works per file.
    pub asset_id: Option<&'a str>,
    pub status: PreviewStatus,
    /// Time spent on the preview itself (zero when none was attempted).
    pub elapsed: Duration,
    /// Items settled so far, including this one, and the number of items
    /// the scope resolved to.
    pub processed: usize,
    pub total: usize,
}

/// Counters of a preview run.
#[derive(Debug, Default, serde::Serialize)]
pub struct PreviewGenerateResult {
    pub generated: usize,
    pub skipped: usize,
    pub failed: usize,
    /// Of `generated`: previews regenerated by `upgrade`.
    pub upgraded: usize,
    /// One line per failure (`<subject>: <error>`), subject being the file
    /// path (`Paths` scope) or the asset id.
    pub errors: Vec<String>,
    /// Labels of offline volumes that held the only locations of skipped
    /// variants, sorted — tells the user which disk to mount.
    pub offline_blockers: Vec<String>,
}

impl AssetService {
    // ═══ GENERATE PREVIEWS ═══

    /// Generate (or regenerate) previews for the files of `scope`.
    ///
    /// `Paths` looks each file up in the catalog; `Asset` and `All` pick
    /// each asset's preview representative (the user's `preview_variant`
    /// override or the best-variant rule), backfill missing video/audio
    /// metadata from a reachable file, and honor the asset's
    /// `preview_rotation`. `on_item` fires once per settled item.
    pub fn generate_previews(
        &self,
        scope: &PreviewScope,
        options: &PreviewOptions,
        on_item: impl FnMut(PreviewEvent<'_>),
    ) -> Result<PreviewGenerateResult> {
        let registry = DeviceRegistry::new(&self.catalog_root);
        let mut run = PreviewRun {
            service: self,
            catalog: Catalog::open(&self.catalog_root)?,
            preview_gen: self.preview_generator(),
            volumes: registry.list()?,
            options,
            result: PreviewGenerateResult::default(),
            offline_blockers: HashSet::new(),
            processed: 0,
            total: 0,
            on_item,
        };

        match scope {
            PreviewScope::Paths(paths) => {
                let files = resolve_files(paths, &self.config.import.exclude);
                let content_store = ContentStore::new(&self.catalog_root);
                run.total = files.len();
                for file_path in &files {
                    run.generate_for_file(&content_store, file_path)?;
                }
            }
            PreviewScope::Asset(_) | PreviewScope::All => {
                let volume_filter = match &options.volume {
                    Some(label) => Some(registry.resolve_volume(label)?),
                    None => None,
                };
                let metadata_store = MetadataStore::new(&self.catalog_root);
                let assets = match scope {
                    PreviewScope::Asset(id) => {
                        let full_id = run.catalog.resolve_asset_id_required(id)?;
                        let uuid: Uuid = full_id.parse()?;
                        vec![metadata_store.load(uuid)?]
                    }
                    _ => metadata_store
                        .list()?
                        .iter()
                        .map(|s| metadata_store.load(s.id))
                        .collect::<Result<Vec<_>>>()?,
                };
                run.total = assets.len();
                for asset in &assets {
                    run.generate_for_asset(asset, volume_filter.as_ref());
                }
            }
        }

        let mut labels: Vec<String> = run.offline_blockers.into_iter().collect();
        labels.sort();
        run.result.offline_blockers = labels;
        Ok(run.result)
    }
}

/// One preview run in progress.
struct PreviewRun<'a, F> {
    service: &'a AssetService,
    catalog: Catalog,
    preview_gen: crate::preview::PreviewGenerator,
    volumes: Vec<Volume>,
    options: &'a PreviewOptions,
    result: PreviewGenerateResult,
    offline_blockers: HashSet<String>,
    processed: usize,
    total: usize,
    on_item: F,
}

/// Outcome of the preview generator calls for one item.
struct Attempt {
    regular: Result<Option<PathBuf>>,
    smart: Option<Result<Option<PathBuf>>>,
    elapsed: Duration,
}

impl<F: FnMut(PreviewEvent<'_>)> PreviewRun<'_, F> {
    /// Count a status and report it. `NotInCatalog` is reported but not
    /// counted; `SmartFailed` and `MetadataBackfillFailed` count as a
    /// failure without settling the item (its regular preview follows).
    fn report(
        &mut self,
        path: Option<&Path>,
        asset_id: Option<&str>,
        status: PreviewStatus,
        elapsed: Duration,
    ) {
        let subject = asset_id
            .map(str::to_string)
            .or_else(|| path.map(|p| p.display().to_string()))
            .unwrap_or_default();
        let settles = match &status {
            PreviewStatus::Generated => {
                self.result.generated += 1;
                true
            }
            PreviewStatus::Upgraded => {
                self.result.generated += 1;
                self.result.upgraded += 1;
                true
            }
            PreviewStatus::Skipped
            | PreviewStatus::NoVariant
            | PreviewStatus::Filtered
            | PreviewStatus::NotUpgradable
            | PreviewStatus::Unreachable => {
                self.result.skipped += 1;
                true
            }
            PreviewStatus::NotInCatalog => true,
            PreviewStatus::Failed(e) => {
                self.result.failed += 1;
                self.result.errors.push(format!("{subject}: {e}"));
                true
            }
            PreviewStatus::SmartFailed(e) | PreviewStatus::MetadataBackfillFailed(e) => {
                self.result.failed += 1;
                self.result.errors.push(format!("{subject}: {e}"));
                false
            }
        };
        if settles {
            self.processed += 1;
        }
        (self.on_item)(PreviewEvent {
            path,
            asset_id,
            status,
            elapsed,
            processed: self.processed,
            total: self.total,
        });
    }

    /// Run the generator (regular, then smart when requested) for one
    /// variant file.
    fn attempt(&self, content_hash: &str, path: &Path, format: &str, rotation: Option<u16>, regenerate: bool) -> Attempt {
        let start = Instant::now();
        let regular = if regenerate {
            self.preview_gen.regenerate_with_rotation(content_hash, path, format, rotation)
        } else {
            self.preview_gen.generate(content_hash, path, format)
        };
        let smart = if self.options.smart {
            Some(if regenerate {
                self.preview_gen.regenerate_smart_with_rotation(content_hash, path, format, rotation)
            } else {
                self.preview_gen.generate_smart(content_hash, path, format)
            })
        } else {
            None
        };
        Attempt {
            regular,
            smart,
            elapsed: start.elapsed(),
        }
    }

    /// Report an attempt: a failed smart preview counts the item as failed
    /// once (not twice when the regular preview already failed).
    fn report_attempt(&mut self, path: &Path, asset_id: Option<&str>, attempt: Attempt, upgraded: bool) {
        let regular_ok = attempt.regular.is_ok();
        if let Some(Err(e)) = attempt.smart {
            if regular_ok {
                self.report(Some(path), asset_id, PreviewStatus::SmartFailed(format!("{e:#}")), attempt.elapsed);
            } else {
                // Reported for the log; the regular failure below counts.
                (self.on_item)(PreviewEvent {
                    path: Some(path),
                    asset_id,
                    status: PreviewStatus::SmartFailed(format!("{e:#}")),
                    elapsed: attempt.elapsed,
                    processed: self.processed,
                    total: self.total,
                });
            }
        }
        let status = match attempt.regular {
            Ok(Some(_)) if upgraded => PreviewStatus::Upgraded,
            Ok(Some(_)) => PreviewStatus::Generated,
            Ok(None) => PreviewStatus::Skipped,
            Err(e) => PreviewStatus::Failed(format!("{e:#}")),
        };
        self.report(Some(path), asset_id, status, attempt.elapsed);
    }

    /// `Paths` scope, one file: look the variant up by volume + path, then
    /// by content hash, and generate its preview.
    fn generate_for_file(&mut self, content_store: &ContentStore, file_path: &Path) -> Result<()> {
        // Filter by extension
        let ext = file_path
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("");
        if !ext.is_empty() && !self.options.filter.is_importable(ext) {
            return Ok(());
        }

        // Look up variant in catalog: try volume+path first, fall back to content hash
        let mut lookup = None;
        if let Some(v) = self.volumes.iter().find(|v| file_path.starts_with(&v.mount_point)) {
            let relative_path = file_path.strip_prefix(&v.mount_point).unwrap_or(file_path);
            lookup = self.catalog.find_variant_by_volume_and_path(
                &v.id.to_string(),
                &crate::path_util::forward_slashes(relative_path),
            )?;
        }
        let lookup = match lookup {
            Some(v) => Some(v),
            None => {
                let hash = content_store.hash_file(file_path)?;
                self.catalog.get_variant_format(&hash)?.map(|fmt| (hash, fmt))
            }
        };

        let Some((content_hash, format)) = lookup else {
            self.report(Some(file_path), None, PreviewStatus::NotInCatalog, Duration::ZERO);
            return Ok(());
        };

        let attempt = self.attempt(&content_hash, file_path, &format, None, self.options.force);
        self.report_attempt(file_path, None, attempt, false);
        Ok(())
    }

    /// Catalog scopes, one asset: pick the preview representative, find a
    /// reachable file for it, backfill video/audio metadata, generate.
    fn generate_for_asset(&mut self, asset: &Asset, volume_filter: Option<&Volume>) {
        let asset_id = asset.id.to_string();
        let upgrade = self.options.upgrade;

        // Select the best variant for preview generation (respects user override)
        let idx = asset
            .preview_variant
            .as_ref()
            .and_then(|h| asset.variants.iter().position(|v| &v.content_hash == h))
            .or_else(|| crate::models::variant::best_preview_index(&asset.variants))
            .unwrap_or(0);
        let Some(variant) = asset.variants.get(idx) else {
            self.report(None, Some(&asset_id), PreviewStatus::NoVariant, Duration::ZERO);
            return;
        };

        // In --upgrade mode, skip assets where the best variant is already the first
        if upgrade && idx == 0 {
            self.report(None, Some(&asset_id), PreviewStatus::NotUpgradable, Duration::ZERO);
            return;
        }

        // Apply format filter
        let ext = &variant.format;
        if !ext.is_empty() && !self.options.filter.is_importable(ext) {
            self.report(None, Some(&asset_id), PreviewStatus::Filtered, Duration::ZERO);
            return;
        }

        // Try to find a reachable file for this variant
        let source_path = variant.locations.iter().find_map(|loc| {
            // Apply volume filter
            if let Some(vf) = volume_filter {
                if loc.volume_id != vf.id {
                    return None;
                }
            }
            self.volumes.iter().find_map(|v| {
                if v.id == loc.volume_id && v.is_online {
                    let full = v.mount_point.join(&loc.relative_path);
                    if full.exists() { Some(full) } else { None }
                } else {
                    None
                }
            })
        });

        let Some(path) = source_path else {
            // Record any offline volume that held a location — so the
            // end-of-run hint can tell the user which disk to mount.
            for loc in &variant.locations {
                if let Some(v) = self.volumes.iter().find(|v| v.id == loc.volume_id) {
                    if !v.is_online {
                        self.offline_blockers.insert(v.label.clone());
                    }
                }
            }
            self.report(None, Some(&asset_id), PreviewStatus::Unreachable, Duration::ZERO);
            return;
        };

        // Backfill video/audio metadata if missing
        let variant_type = determine_asset_type(&variant.format);
        let backfill = if variant_type == AssetType::Video
            && !variant.source_metadata.contains_key("video_duration")
        {
            Some(self.service.backfill_video_metadata(&asset_id, &variant.content_hash, &path))
        } else if variant_type == AssetType::Audio
            && !variant.source_metadata.contains_key("audio_duration")
        {
            Some(self.service.backfill_audio_metadata(&asset_id, &variant.content_hash, &path))
        } else {
            None
        };
        if let Some(Err(e)) = backfill {
            self.report(
                Some(&path),
                Some(&asset_id),
                PreviewStatus::MetadataBackfillFailed(format!("{e:#}")),
                Duration::ZERO,
            );
        }

        let regenerate = self.options.force || upgrade;
        let attempt = self.attempt(&variant.content_hash, &path, &variant.format, asset.preview_rotation, regenerate);
        self.report_attempt(&path, Some(&asset_id), attempt, upgrade);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A catalog with one registered online volume holding one real PNG,
    /// imported. Returns the service, the volume and the file path.
    fn catalog_with_one_image() -> (tempfile::TempDir, tempfile::TempDir, AssetService, PathBuf) {
        let catalog_dir = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(catalog_dir.path().join("metadata")).unwrap();
        crate::config::CatalogConfig::default().save(catalog_dir.path()).unwrap();
        Catalog::open(catalog_dir.path()).unwrap().initialize().unwrap();
        DeviceRegistry::init(catalog_dir.path()).unwrap();

        let vol_dir = tempfile::tempdir().unwrap();
        let volume = DeviceRegistry::new(catalog_dir.path())
            .register("vol1", vol_dir.path(), crate::models::VolumeType::Local, None)
            .unwrap();
        let photo = vol_dir.path().join("photo.png");
        image::RgbImage::new(4, 4).save(&photo).unwrap();

        let service = AssetService::new(
            catalog_dir.path(),
            crate::Verbosity::quiet(),
            &crate::config::PreviewConfig::default(),
        );
        let r = service
            .import(std::slice::from_ref(&photo), &volume, &FileTypeFilter::default())
            .unwrap();
        assert_eq!(r.imported, 1);
        (catalog_dir, vol_dir, service, photo)
    }

    #[test]
    fn generate_previews_all_scope_reports_each_asset_once() {
        let (_c, _v, service, _photo) = catalog_with_one_image();
        let mut events: Vec<(Option<String>, PreviewStatus, usize, usize)> = Vec::new();
        let result = service
            .generate_previews(&PreviewScope::All, &PreviewOptions::default(), |e| {
                events.push((e.asset_id.map(str::to_string), e.status.clone(), e.processed, e.total));
            })
            .unwrap();
        // One asset, settled once.
        assert_eq!(events.len(), 1);
        assert_eq!(events[0].1, PreviewStatus::Generated);
        assert_eq!((events[0].2, events[0].3), (1, 1));
        assert!(events[0].0.is_some());
        assert_eq!((result.generated, result.skipped, result.failed), (1, 0, 0));
        assert!(result.offline_blockers.is_empty());

        // The preview now exists: still reported as in place, and
        // regenerated with `force`.
        let result = service.generate_previews(&PreviewScope::All, &PreviewOptions::default(), |_| {}).unwrap();
        assert_eq!((result.generated, result.skipped, result.failed), (1, 0, 0));
        let options = PreviewOptions { force: true, ..Default::default() };
        let result = service.generate_previews(&PreviewScope::All, &options, |_| {}).unwrap();
        assert_eq!((result.generated, result.skipped, result.failed), (1, 0, 0));
    }

    #[test]
    fn generate_previews_paths_scope_looks_files_up_and_ignores_unknown_ones() {
        let (_c, vol_dir, service, photo) = catalog_with_one_image();
        let unknown = vol_dir.path().join("other.png");
        image::RgbImage::new(2, 2).save(&unknown).unwrap();

        let mut statuses = Vec::new();
        let options = PreviewOptions { force: true, ..Default::default() };
        let result = service
            .generate_previews(&PreviewScope::Paths(vec![photo.clone(), unknown]), &options, |e| {
                assert!(e.asset_id.is_none());
                statuses.push(e.status.clone());
            })
            .unwrap();
        assert_eq!(statuses, vec![PreviewStatus::Generated, PreviewStatus::NotInCatalog]);
        assert_eq!((result.generated, result.skipped, result.failed), (1, 0, 0));
    }

    #[test]
    fn generate_previews_asset_scope_resolves_prefix_and_upgrade_skips_first_variant() {
        let (c, _v, service, _photo) = catalog_with_one_image();
        let id = Catalog::open(c.path()).unwrap().list_all_asset_ids().unwrap().into_iter().next().unwrap();
        let prefix = id[..8].to_string();

        let options = PreviewOptions { upgrade: true, ..Default::default() };
        let mut statuses = Vec::new();
        let result = service
            .generate_previews(&PreviewScope::Asset(prefix), &options, |e| statuses.push(e.status.clone()))
            .unwrap();
        assert_eq!(statuses, vec![PreviewStatus::NotUpgradable]);
        assert_eq!((result.generated, result.skipped, result.upgraded), (0, 1, 0));

        let err = service
            .generate_previews(&PreviewScope::Asset("nope".into()), &PreviewOptions::default(), |_| {})
            .unwrap_err();
        assert!(matches!(crate::error::classify(&err), Some(crate::error::MakiError::NotFound { .. })));
    }
}
